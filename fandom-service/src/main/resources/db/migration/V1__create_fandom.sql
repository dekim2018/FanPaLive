-- 팬덤 서비스 스키마: 종목/리그, 응원 대상(구단/선수), 등록 신청, 팬 등록, 하트 원장, 후원 반영 원장, 집계, 경기, 랭킹 스냅샷

CREATE TABLE sports
(
    code       VARCHAR(20) PRIMARY KEY,
    name       VARCHAR(20) NOT NULL,
    kind       VARCHAR(12) NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    CONSTRAINT chk_sports_kind CHECK (kind IN ('TEAM', 'INDIVIDUAL'))
);

CREATE TABLE leagues
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_code       VARCHAR(20) NOT NULL REFERENCES sports (code),
    code             VARCHAR(20) NOT NULL UNIQUE,
    name             VARCHAR(40) NOT NULL,
    country          VARCHAR(20) NOT NULL DEFAULT '',
    open_for_request BOOLEAN     NOT NULL DEFAULT TRUE,
    sort_order       INTEGER     NOT NULL DEFAULT 0
);

CREATE TABLE fan_targets
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id       BIGINT                   NOT NULL REFERENCES leagues (id),
    kind            VARCHAR(10)              NOT NULL,
    name            VARCHAR(40)              NOT NULL,
    name_en         VARCHAR(60),
    normalized_name VARCHAR(80)              NOT NULL,
    short_name      VARCHAR(6)               NOT NULL,
    color_primary   VARCHAR(7)               NOT NULL,
    color_secondary VARCHAR(7)               NOT NULL,
    description     VARCHAR(300)             NOT NULL DEFAULT '',
    status          VARCHAR(10)              NOT NULL,
    official        BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_by      BIGINT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_fan_targets_league_name UNIQUE (league_id, normalized_name),
    CONSTRAINT chk_fan_targets_kind CHECK (kind IN ('TEAM', 'PLAYER')),
    CONSTRAINT chk_fan_targets_status CHECK (status IN ('ACTIVE', 'HIDDEN'))
);

CREATE INDEX idx_fan_targets_league ON fan_targets (league_id, status);

CREATE TABLE target_requests
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id          BIGINT                   NOT NULL REFERENCES leagues (id),
    kind               VARCHAR(10)              NOT NULL,
    name               VARCHAR(40)              NOT NULL,
    name_en            VARCHAR(60),
    normalized_name    VARCHAR(80)              NOT NULL,
    short_name         VARCHAR(6)               NOT NULL,
    color_primary      VARCHAR(7)               NOT NULL,
    color_secondary    VARCHAR(7)               NOT NULL,
    description        VARCHAR(300)             NOT NULL DEFAULT '',
    reference_url      VARCHAR(300),
    status             VARCHAR(10)              NOT NULL,
    reject_reason      VARCHAR(200),
    requester_id       BIGINT                   NOT NULL,
    requester_nickname VARCHAR(20)              NOT NULL,
    vote_count         INTEGER                  NOT NULL DEFAULT 1,
    target_id          BIGINT,
    decided_by         BIGINT,
    decided_at         TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_target_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- 같은 리그에 같은 이름(정규화 기준)으로 열린 신청은 하나만 둔다. 동시에 두 명이 신청해도 DB 가 막는다.
CREATE UNIQUE INDEX uk_target_requests_open_name ON target_requests (league_id, normalized_name)
    WHERE status = 'PENDING';
CREATE INDEX idx_target_requests_status_votes ON target_requests (status, vote_count DESC, created_at);
CREATE INDEX idx_target_requests_requester ON target_requests (requester_id, created_at DESC);

CREATE TABLE target_request_votes
(
    request_id    BIGINT                   NOT NULL REFERENCES target_requests (id),
    user_id       BIGINT                   NOT NULL,
    user_nickname VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (request_id, user_id)
);

CREATE TABLE fan_memberships
(
    user_id       BIGINT                   NOT NULL,
    target_id     BIGINT                   NOT NULL REFERENCES fan_targets (id),
    league_id     BIGINT                   NOT NULL,
    user_nickname VARCHAR(20)              NOT NULL,
    primary_fan   BOOLEAN                  NOT NULL DEFAULT FALSE,
    joined_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, target_id)
);

-- 리그당 주 응원팀은 하나뿐이다(애플리케이션 규칙을 DB 에서도 보장).
CREATE UNIQUE INDEX uk_fan_memberships_primary ON fan_memberships (user_id, league_id) WHERE primary_fan;
CREATE INDEX idx_fan_memberships_target ON fan_memberships (target_id);

CREATE TABLE primary_fan_changes
(
    user_id    BIGINT                   NOT NULL,
    league_id  BIGINT                   NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, league_id)
);

-- 조회용 집계(읽기 모델). 원장은 heart_logs, donation_contributions, fan_memberships 다.
CREATE TABLE target_stats
(
    target_id      BIGINT PRIMARY KEY REFERENCES fan_targets (id),
    primary_fans   BIGINT                   NOT NULL DEFAULT 0,
    follow_fans    BIGINT                   NOT NULL DEFAULT 0,
    hearts_total   BIGINT                   NOT NULL DEFAULT 0,
    donation_total BIGINT                   NOT NULL DEFAULT 0,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_target_stats_fans ON target_stats ((primary_fans + follow_fans) DESC);

CREATE TABLE target_stats_daily
(
    target_id         BIGINT                   NOT NULL,
    stat_date         DATE                     NOT NULL,
    hearts            BIGINT                   NOT NULL DEFAULT 0,
    heart_points      BIGINT                   NOT NULL DEFAULT 0,
    suspicious_hearts BIGINT                   NOT NULL DEFAULT 0,
    donation_amount   BIGINT                   NOT NULL DEFAULT 0,
    last_activity_at  TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (target_id, stat_date)
);

CREATE INDEX idx_target_stats_daily_date ON target_stats_daily (stat_date);

-- 하트 원장. 200ms 마다 배치 INSERT 로 쌓인다.
CREATE TABLE heart_logs
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    user_nickname VARCHAR(20)              NOT NULL,
    target_id     BIGINT                   NOT NULL,
    match_id      BIGINT,
    amount        INTEGER                  NOT NULL,
    points        INTEGER                  NOT NULL,
    source        VARCHAR(12)              NOT NULL,
    suspicious    BOOLEAN                  NOT NULL DEFAULT FALSE,
    given_date    DATE                     NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_heart_logs_target_created ON heart_logs (target_id, created_at);
CREATE INDEX idx_heart_logs_user_created ON heart_logs (user_id, created_at DESC);

-- 후원 반영 원장. event_id 가 PK 라서 같은 이벤트를 두 번 반영할 수 없다(멱등 소비).
CREATE TABLE donation_contributions
(
    event_id       VARCHAR(64) PRIMARY KEY,
    target_id      BIGINT                   NOT NULL,
    donor_id       BIGINT                   NOT NULL,
    donor_nickname VARCHAR(20)              NOT NULL,
    amount         BIGINT                   NOT NULL,
    approved_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_donation_contributions_target ON donation_contributions (target_id, approved_at);

CREATE TABLE matches
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id      BIGINT                   NOT NULL REFERENCES leagues (id),
    home_target_id BIGINT                   NOT NULL REFERENCES fan_targets (id),
    away_target_id BIGINT                   NOT NULL REFERENCES fan_targets (id),
    starts_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    status         VARCHAR(10)              NOT NULL,
    home_score     INTEGER                  NOT NULL DEFAULT 0,
    away_score     INTEGER                  NOT NULL DEFAULT 0,
    venue          VARCHAR(40)              NOT NULL DEFAULT '',
    created_by     BIGINT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_matches_status CHECK (status IN ('SCHEDULED', 'LIVE', 'FINISHED', 'CANCELED')),
    CONSTRAINT chk_matches_teams CHECK (home_target_id <> away_target_id)
);

CREATE INDEX idx_matches_starts ON matches (starts_at, league_id);

CREATE TABLE ranking_snapshots
(
    league_id   BIGINT                   NOT NULL,
    period_type VARCHAR(10)              NOT NULL,
    period_key  VARCHAR(12)              NOT NULL,
    target_id   BIGINT                   NOT NULL,
    rank        INTEGER                  NOT NULL,
    score       BIGINT                   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (league_id, period_type, period_key, target_id)
);

CREATE INDEX idx_ranking_snapshots_target ON ranking_snapshots (target_id, period_type, period_key DESC);

CREATE TABLE reconcile_logs
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stat_date  DATE                     NOT NULL,
    target_id  BIGINT                   NOT NULL,
    expected   BIGINT                   NOT NULL,
    actual     BIGINT                   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
