-- 6장 추가 기능: 응원팀 방송 알림, 팬 포인트와 등급, 승부 예측, 명예의 전당

-- 사이트 안 알림. (user_id, event_id) 가 유일해서 같은 이벤트로 두 번 알리지 않는다.
CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    event_id   VARCHAR(80)              NOT NULL,
    type       VARCHAR(20)              NOT NULL,
    title      VARCHAR(120)             NOT NULL,
    body       VARCHAR(200)             NOT NULL DEFAULT '',
    link       VARCHAR(200),
    target_id  BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_notifications_user_event UNIQUE (user_id, event_id),
    CONSTRAINT chk_notifications_type CHECK (type IN ('BROADCAST_LIVE', 'PREDICTION_RESULT'))
);

CREATE INDEX idx_notifications_user ON notifications (user_id, id DESC);
-- 안 읽은 알림 수는 자주 세지만 대부분 읽은 상태라 부분 인덱스로 작게 유지한다.
CREATE INDEX idx_notifications_unread ON notifications (user_id) WHERE read_at IS NULL;

-- 팬 포인트 원장. 같은 근거(reason, ref_key)로 두 번 쌓이지 않는다.
CREATE TABLE fan_point_ledger
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    user_nickname VARCHAR(20)              NOT NULL,
    target_id     BIGINT,
    reason        VARCHAR(12)              NOT NULL,
    ref_key       VARCHAR(80)              NOT NULL,
    points        INTEGER                  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_point_ledger_ref UNIQUE (user_id, reason, ref_key),
    CONSTRAINT chk_point_ledger_reason CHECK (reason IN ('HEART', 'DONATION', 'PREDICTION')),
    CONSTRAINT chk_point_ledger_points CHECK (points > 0)
);

-- 사용자별 합계(읽기 모델). 원장에 새로 쌓일 때 같은 트랜잭션에서 더한다.
CREATE TABLE fan_profiles
(
    user_id        BIGINT PRIMARY KEY,
    nickname       VARCHAR(20)              NOT NULL,
    points         BIGINT                   NOT NULL DEFAULT 0,
    heart_days     INTEGER                  NOT NULL DEFAULT 0,
    donation_count INTEGER                  NOT NULL DEFAULT 0,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 승부 예측(사용자당 경기마다 하나). 보상은 포인트뿐이다.
CREATE TABLE match_predictions
(
    match_id      BIGINT                   NOT NULL REFERENCES matches (id),
    user_id       BIGINT                   NOT NULL,
    user_nickname VARCHAR(20)              NOT NULL,
    pick          VARCHAR(4)               NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    result        VARCHAR(4),
    settled_at    TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (match_id, user_id),
    CONSTRAINT chk_predictions_pick CHECK (pick IN ('HOME', 'AWAY')),
    CONSTRAINT chk_predictions_result CHECK (result IS NULL OR result IN ('HIT', 'MISS', 'VOID'))
);

CREATE INDEX idx_predictions_user ON match_predictions (user_id, created_at DESC);

-- 명예의 전당: 시즌 최종 순위는 ranking_snapshots(period_type = SEASON)에, 우승팀 MVP 팬은 여기에 둔다.
CREATE TABLE season_mvps
(
    league_id  BIGINT                   NOT NULL,
    season_key VARCHAR(12)              NOT NULL,
    target_id  BIGINT                   NOT NULL,
    user_id    BIGINT                   NOT NULL,
    nickname   VARCHAR(20)              NOT NULL,
    points     BIGINT                   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (league_id, season_key)
);

-- 일정 가져오기에서 같은 경기를 빨리 찾기 위한 인덱스
CREATE INDEX idx_matches_slot ON matches (league_id, home_target_id, away_target_id, starts_at);
