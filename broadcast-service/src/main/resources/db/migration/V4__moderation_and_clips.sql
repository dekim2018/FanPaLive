ALTER TABLE broadcasts
    ADD COLUMN moderated_at      TIMESTAMP WITH TIME ZONE,
    ADD COLUMN moderation_reason VARCHAR(200);

-- 하이라이트 클립: 녹화 파일을 복사하지 않고 구간(시작 시각, 길이)만 기록한다.
CREATE TABLE clips
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recording_id       BIGINT                   NOT NULL REFERENCES recordings (id) ON DELETE CASCADE,
    broadcast_id       BIGINT                   NOT NULL,
    recording_owner_id BIGINT                   NOT NULL,
    media_path         VARCHAR(50)              NOT NULL,
    creator_id         BIGINT                   NOT NULL,
    creator_nickname   VARCHAR(20)              NOT NULL,
    title              VARCHAR(60)              NOT NULL,
    offset_seconds     BIGINT                   NOT NULL,
    duration_seconds   INTEGER                  NOT NULL,
    start_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    league_code        VARCHAR(20),
    target_id          BIGINT,
    target_name        VARCHAR(40),
    target_short_name  VARCHAR(6),
    target_color       VARCHAR(7),
    target_text_color  VARCHAR(7),
    match_id           BIGINT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_clips_duration CHECK (duration_seconds BETWEEN 5 AND 60),
    CONSTRAINT chk_clips_offset CHECK (offset_seconds >= 0)
);

CREATE INDEX idx_clips_recording ON clips (recording_id, id DESC);
CREATE INDEX idx_clips_target ON clips (target_id, id DESC);
CREATE INDEX idx_clips_created ON clips (id DESC);
