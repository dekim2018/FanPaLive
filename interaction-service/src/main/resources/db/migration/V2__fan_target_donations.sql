-- 구단/선수 응원기금(방송자가 없는 후원)과 결제 결과를 모르는 상태(UNKNOWN)를 지원한다.

ALTER TABLE donations ADD COLUMN target_type VARCHAR(12) NOT NULL DEFAULT 'BROADCAST';
ALTER TABLE donations ADD COLUMN target_id BIGINT;
ALTER TABLE donations ADD COLUMN target_name VARCHAR(40);

ALTER TABLE donations ALTER COLUMN broadcast_id DROP NOT NULL;
ALTER TABLE donations ALTER COLUMN streamer_id DROP NOT NULL;
ALTER TABLE donations ALTER COLUMN streamer_nickname DROP NOT NULL;

-- 방송자 후원은 방송과 방송자가 반드시 있고, 응원기금은 응원 대상이 반드시 있다.
ALTER TABLE donations ADD CONSTRAINT chk_donation_target CHECK (
    (target_type = 'BROADCAST' AND broadcast_id IS NOT NULL AND streamer_id IS NOT NULL
        AND streamer_nickname IS NOT NULL)
    OR (target_type = 'FAN_TARGET' AND target_id IS NOT NULL AND broadcast_id IS NULL AND streamer_id IS NULL)
);

ALTER TABLE donations DROP CONSTRAINT chk_donation_status;
ALTER TABLE donations ADD CONSTRAINT chk_donation_status CHECK (status IN ('PENDING', 'UNKNOWN', 'DONE', 'FAILED'));

CREATE INDEX idx_donations_target_status ON donations (target_id, status, approved_at DESC) WHERE target_id IS NOT NULL;
CREATE INDEX idx_donations_donor_status ON donations (donor_id, status, approved_at DESC);
CREATE INDEX idx_donations_streamer_status ON donations (streamer_id, status, approved_at DESC)
    WHERE streamer_id IS NOT NULL;
CREATE INDEX idx_donations_status_approved ON donations (status, approved_at);
-- 결과 확인 작업이 UNKNOWN 만 빠르게 찾도록 부분 인덱스를 둔다(평소에는 거의 비어 있다).
CREATE INDEX idx_donations_unknown ON donations (updated_at) WHERE status = 'UNKNOWN';

-- 결제사 거래 내역과 비교한 결과 중 사람이 확인해야 하거나 자동 보정한 건
CREATE TABLE payment_reconcile_logs
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   VARCHAR(64)              NOT NULL,
    issue      VARCHAR(30)              NOT NULL,
    detail     VARCHAR(200),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_payment_reconcile_logs_created ON payment_reconcile_logs (created_at DESC);
