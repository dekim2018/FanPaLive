-- 신고. 같은 사람이 같은 대상을 두 번 신고할 수 없다.
CREATE TABLE reports
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type              VARCHAR(10)              NOT NULL,
    ref_id            BIGINT                   NOT NULL,
    broadcast_id      BIGINT,
    reporter_id       BIGINT                   NOT NULL,
    reporter_nickname VARCHAR(20)              NOT NULL,
    reason            VARCHAR(20)              NOT NULL,
    detail            VARCHAR(200)             NOT NULL DEFAULT '',
    snapshot          VARCHAR(300)             NOT NULL DEFAULT '',
    subject_user_id   BIGINT,
    status            VARCHAR(10)              NOT NULL DEFAULT 'OPEN',
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at       TIMESTAMP WITH TIME ZONE,
    resolved_by       BIGINT,
    CONSTRAINT uk_reports_reporter_target UNIQUE (reporter_id, type, ref_id),
    CONSTRAINT chk_reports_type CHECK (type IN ('BROADCAST', 'COMMENT')),
    CONSTRAINT chk_reports_reason CHECK (reason IN ('RIGHTS_VIOLATION', 'ABUSE', 'SPAM', 'ETC')),
    CONSTRAINT chk_reports_status CHECK (status IN ('OPEN', 'ACTIONED', 'DISMISSED'))
);

CREATE INDEX idx_reports_status ON reports (status, id DESC);
CREATE INDEX idx_reports_target_open ON reports (type, ref_id) WHERE status = 'OPEN';

